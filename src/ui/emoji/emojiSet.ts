/**
 * The emoji offered by the picker.
 *
 * Grouped and ordered the way Unicode groups them, because that is the order
 * every system keyboard uses and people navigate by muscle memory rather than
 * by reading headings. The categories are the CLDR ones: Smileys & Emotion,
 * People & Body, Animals & Nature, Food & Drink, Activities, Travel & Places,
 * Objects, Symbols. Flags are left out — there are 260 of them, they are the
 * least used category by a wide margin, and several are politically contested
 * in ways a messenger has no business adjudicating.
 *
 * Curated rather than generated. A full Unicode emoji database with names,
 * keywords and search indexes runs to several hundred kilobytes — larger than
 * the entire application shell — and would be downloaded by everyone who ever
 * opens the picker. These are the ones people actually send, in the order they
 * expect to find them.
 *
 * No skin-tone variants: they multiply the list fivefold, and the modifier is
 * accepted by the reaction validator anyway, so an emoji pasted from a system
 * keyboard still works. Every entry here is checked against that validator by
 * `tests/emojiSet.test.ts`, so the picker can never offer something that the
 * reaction path would reject.
 */

